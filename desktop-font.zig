pub fn drawChar(pixels: [*]u32, stride: usize, x0: usize, y0: usize, ch: u8, scale: usize, color: u32) void {
    const idx: usize = if (ch >= 32 and ch < 127) ch - 32 else if (ch == 0x26 or ch == 127) 95 else return;
    const glyph = glyphs[idx];
    for (0..glyph_height) |row| {
        const bits = glyph[row];
        if (bits == 0) continue;
        for (0..glyph_width) |col| {
            if ((bits & (@as(u8, 1) << @intCast(col))) != 0) {
                for (0..scale) |dy| {
                    for (0..scale) |dx| {
                        pixels[(y0 + row * scale + dy) * stride + (x0 + col * scale + dx)] = color;
                    }
                }
            }
        }
    }
}

pub fn drawText(pixels: [*]u32, stride: usize, x0: usize, y0: usize, text: []const u8, scale: usize, color: u32) void {
    var cur_x = x0;
    var i: usize = 0;
    while (i < text.len) {
        if (std.mem.startsWith(u8, text[i..], "…")) {
            drawChar(pixels, stride, cur_x, y0, 127, scale, color);
            cur_x += glyph_width * scale;
            i += 3;
        } else {
            drawChar(pixels, stride, cur_x, y0, text[i], scale, color);
            cur_x += glyph_width * scale;
            i += 1;
        }
    }
}

pub fn textWidth(text: []const u8, scale: usize) usize {
    var count: usize = 0;
    var i: usize = 0;
    while (i < text.len) {
        if (std.mem.startsWith(u8, text[i..], "…")) {
            count += 1;
            i += 3;
        } else {
            count += 1;
            i += 1;
        }
    }
    return count * glyph_width * scale;
}
